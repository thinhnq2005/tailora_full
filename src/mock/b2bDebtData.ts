export function calculateDebtMetrics(
  customers: B2bCustomer[] = INITIAL_B2B_CUSTOMERS,
  vouchers: B2bVoucher[] = INITIAL_B2B_VOUCHERS
): DebtDashboardMetrics {
  const tongCongNo = customers.reduce((sum, c) => sum + c.duNoHienTai, 0);
  
  const congNoQuaHan = vouchers
    .filter(v => v.trangThai === 'Quá hạn')
    .reduce((sum, v) => sum + v.conNo, 0);

  const daThanhToan = vouchers.reduce((sum, v) => sum + v.daThanhToan, 0);
  const chuaThanhToan = vouchers
    .filter(v => v.trangThai === 'Trong hạn' || v.trangThai === 'Cảnh báo')
    .reduce((sum, v) => sum + v.conNo, 0);

  const khachHangQuaHan = customers.filter(c => c.trangThai === 'Quá hạn').length;

  return {
    tongCongNo,
    congNoQuaHan,
    daThanhToan,
    chuaThanhToan,
    tongKhachHang: customers.length,
    khachHangQuaHan
  };
}
